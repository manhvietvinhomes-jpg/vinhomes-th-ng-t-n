import fs from 'node:fs';
import {TEN_POSTS} from '../src/articles.js';
const posts=JSON.parse(fs.readFileSync('content/guides/74-bai-cam-nang.json','utf8'));
if(posts.length!==74||new Set(posts.map(p=>p.slug)).size!==74)throw Error('Bộ cẩm nang phải có 74 chủ đề duy nhất.');
fs.writeFileSync('src/guides.js','// Generated by npm run content:sync from the editorial JSON.\nexport const GUIDE_POSTS = '+JSON.stringify(posts,null,2)+';\n');
const all=[...TEN_POSTS,...posts];
fs.writeFileSync('content/keyword-map.json',JSON.stringify({updated:'2026-10-27',articles:all.map(p=>({slug:p.slug,title:p.title,keyword:p.keyword,topic:p.category||p.topic||'Phân tích dự án'}))},null,2)+'\n');
fs.writeFileSync('public/noi-dung-seo.json',JSON.stringify({version:3,posts:all},null,2)+'\n');
for(const file of ['content/noi-dung-10-bai.json','public/noi-dung-10-bai.json'])fs.writeFileSync(file,JSON.stringify({version:2,posts:TEN_POSTS},null,2)+'\n');
const {INITIAL_CONTENT}=await import('../src/seed.js');
fs.writeFileSync('public/seed.json',JSON.stringify(INITIAL_CONTENT,null,2)+'\n');
console.log(`Đồng bộ ${all.length} bài xuất bản; không thay nội dung KV hiện có.`);
